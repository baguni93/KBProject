    /** 전체 공식 BIN Set (299건 + 커스텀 4건 통합) */
    public static final Set<String> ALL_OFFICIAL_BINS = new HashSet<>();

    static {
        ALL_OFFICIAL_BINS.addAll(CREDIT_BINS);
        ALL_OFFICIAL_BINS.addAll(CHECK_BINS);
        ALL_OFFICIAL_BINS.addAll(CUSTOM_BINS);
        ALL_OFFICIAL_BINS.addAll(PREPAID_BINS);
    }

    /**
     * 입력된 번호가 KB국민카드 299개 공식 명세서 또는 커스텀 풀에 존재하는지 판별
     */
    public static boolean isOfficialBin(String binNumber) {
        if (binNumber == null) return false;
        String clean = binNumber.replaceAll("\\D", "");
        if (clean.length() >= 8 && ALL_OFFICIAL_BINS.contains(clean.substring(0, 8))) {
            return true;
        }
        if (clean.length() >= 6 && ALL_OFFICIAL_BINS.contains(clean.substring(0, 6))) {
            return true;
        }
        return false;
    }

    /**
     * 카드의 타입 및 인덱스를 기반으로 중복 없이 공식 BIN 할당
     */
    public static String getBinForCard(int index, String cardType, String cardName) {
        boolean isCheck = (cardType != null && "CHECK".equalsIgnoreCase(cardType))
                || (cardName != null && cardName.contains("체크"));

        if (isCheck) {
            int targetIdx = Math.abs(index) % CHECK_BINS.size();
            return CHECK_BINS.get(targetIdx);
        } else {
            int targetIdx = Math.abs(index) % CREDIT_BINS.size();
            return CREDIT_BINS.get(targetIdx);
        }
    }
